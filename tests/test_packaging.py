"""What gets published: the source distribution ships what the repository tracks, the wheel ships the whole package
(its SQL, packs, templates and static files too), and neither picks up a file that only exists on this machine."""
from __future__ import annotations

import email
import re
import shutil
import subprocess
import tarfile
import tomllib
import zipfile
from email.message import Message
from pathlib import Path

import pytest

ROOT = Path(__file__).parents[1]
VERSION_FILE = ROOT / "src" / "benchbook" / "_version.py"
# One file of each kind the package reads at run time and Python packaging does not pick up by itself.
RUNTIME_FILES = (
    "benchbook/py.typed",
    "benchbook/_version.py",  # generated by the build and ignored by git: the build identity of an install
    "benchbook/db/alembic/script.py.mako",
    "benchbook/db/alembic/sql/0001_core.sql",
    "benchbook/packs/core/pack.toml",
    "benchbook/packs/core/schemas/experiment.config.json",
    "benchbook/integrations/autoresearch/templates/program.benchbook.md",
    "benchbook/web/templates/base.html",
    "benchbook/web/static/benchbook.css",
)


def _git_files(*args: str) -> set[str]:
    """Paths git lists for these ls-files arguments that exist as files in the working tree."""
    try:
        out = subprocess.run(["git", "ls-files", "-z", *args], cwd=ROOT, capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        pytest.skip("not a git checkout")
    return {f for f in out.stdout.split("\0") if f and (ROOT / f).is_file()}


def test_sdist_only_include_matches_tracked_top_level() -> None:
    top = {f.split("/", 1)[0] for f in _git_files()}
    config = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    only = set(config["tool"]["hatch"]["build"]["targets"]["sdist"]["only-include"])
    assert only == top


@pytest.fixture(scope="module")
def dists(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    """The sdist and the wheel of this checkout, built the way the release workflow builds them (`uv build`: the
    sdist from the tree, the wheel from that sdist)."""
    if shutil.which("uv") is None:
        pytest.skip("uv is not on PATH")
    if not (ROOT / ".git").exists():
        pytest.skip("not a git checkout")
    out = tmp_path_factory.mktemp("dist")
    # The build rewrites the version file in the source tree, with a different value when the tree has uncommitted
    # changes. This session already imported the old one and later tests compare it with a subprocess, so put it back.
    before = VERSION_FILE.read_bytes() if VERSION_FILE.exists() else None
    try:
        p = subprocess.run(["uv", "build", "--no-sources", "--out-dir", str(out)], cwd=ROOT, capture_output=True,
                           text=True, timeout=600)
    finally:
        if before is None:
            VERSION_FILE.unlink(missing_ok=True)
        else:
            VERSION_FILE.write_bytes(before)
    assert p.returncode == 0, p.stdout + p.stderr
    (sdist,) = out.glob("benchbook-*.tar.gz")
    (wheel,) = out.glob("benchbook-*-py3-none-any.whl")
    return sdist, wheel


def _between(shipped: set[str], required: set[str], allowed: set[str]) -> None:
    assert not required - shipped, f"tracked but not shipped: {sorted(required - shipped)}"
    assert not shipped - allowed, f"shipped but not in the repository: {sorted(shipped - allowed)}"


def test_wheel_ships_the_whole_package_and_nothing_local(dists: tuple[Path, Path]) -> None:
    with zipfile.ZipFile(dists[1]) as z:
        names = {n for n in z.namelist() if not n.endswith("/")}
    package = {n for n in names if n.startswith("benchbook/")}
    for f in RUNTIME_FILES:
        assert f in package, f
    # every SQL file a migration revision runs
    for rev in _git_files("src/benchbook/db/alembic/versions"):
        assert f"benchbook/db/alembic/sql/{Path(rev).stem}.sql" in package, rev
    tracked = {f.removeprefix("src/") for f in _git_files("src/benchbook")}
    # New files not added yet may ship; files that only git's local or global excludes hide (hatch reads .gitignore
    # alone) may not.
    known = {f.removeprefix("src/") for f in _git_files("--cached", "--others", "--exclude-standard", "src/benchbook")}
    _between(package, tracked, known | {"benchbook/_version.py"})
    # nothing beside the package: no tests, bench or examples in site-packages
    assert all(re.match(r"benchbook-[^/]+\.dist-info/", n) for n in names - package), sorted(names - package)


def test_sdist_ships_the_tracked_files_and_nothing_local(dists: tuple[Path, Path]) -> None:
    with tarfile.open(dists[0]) as t:
        names = {m.name.split("/", 1)[1] for m in t.getmembers() if m.isfile()}
    known = _git_files("--cached", "--others", "--exclude-standard")
    _between(names, _git_files(), known | {"PKG-INFO", "src/benchbook/_version.py"})


def _wheel_text(wheel: Path, suffix: str) -> str:
    with zipfile.ZipFile(wheel) as z:
        (name,) = (n for n in z.namelist() if n.endswith(suffix))
        return z.read(name).decode("utf-8")


def test_wheel_metadata_is_what_pypi_shows(dists: tuple[Path, Path]) -> None:
    wheel = dists[1]
    meta: Message = email.message_from_string(_wheel_text(wheel, ".dist-info/METADATA"))
    assert meta["Name"] == "benchbook"
    # one version everywhere: the file name, the metadata and what `benchbook --version` prints from the install
    version = wheel.name.split("-")[1]
    assert meta["Version"] == version
    assert re.search(rf"^__version__ = version = '{re.escape(version)}'$", _wheel_text(wheel, "benchbook/_version.py"),
                     re.M)
    assert meta["License-Expression"] == "Apache-2.0"
    assert meta["Requires-Python"] == ">=3.11"
    assert meta["Description-Content-Type"] == "text/markdown" and "# benchbook" in str(meta.get_payload())
    urls = dict(u.split(", ", 1) for u in meta.get_all("Project-URL") or [])
    assert {"Homepage", "Repository", "Issues", "Changelog"} <= set(urls)
    assert all(u.startswith("https://") for u in urls.values()), urls
    classifiers = set(meta.get_all("Classifier") or [])
    assert "Typing :: Typed" in classifiers
    config = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert classifiers == set(config["project"]["classifiers"])
    assert meta["Keywords"]
    assert re.search(r"^benchbook = benchbook\.entry:main$", _wheel_text(wheel, ".dist-info/entry_points.txt"), re.M)
